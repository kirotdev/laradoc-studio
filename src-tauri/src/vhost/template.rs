/// Generate an Nginx virtual host configuration for a *.test project
pub fn generate_nginx_vhost(
    project_name: &str,
    domain: &str,
    doc_root: &str,
    ssl_dir: &str,
    php_pool_port: &str,
) -> String {
    format!(
        r#"# Auto-generated by Laradoc Studio — DO NOT EDIT MANUALLY
# Project: {project_name}

server {{
    listen 80;
    server_name {domain};
    return 301 https://$host$request_uri;
}}

server {{
    listen 443 ssl;
    http2 on;
    server_name {domain};

    root {doc_root};
    index index.php index.html;

    ssl_certificate {ssl_dir}/wildcard.test.crt;
    ssl_certificate_key {ssl_dir}/wildcard.test.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 10m;

    location / {{
        try_files $uri $uri/ /index.php?$query_string;
    }}

    location ~ \.php$ {{
        fastcgi_pass 127.0.0.1:{php_pool_port};
        fastcgi_index index.php;
        fastcgi_param SCRIPT_FILENAME $realpath_root$fastcgi_script_name;
        include fastcgi_params;
        fastcgi_param PHP_VALUE "error_log={doc_root}/../storage/logs/php_errors.log";
    }}

    location ~ /\.(?!well-known).* {{
        deny all;
    }}

    access_log off;
    error_log /dev/null crit;
}}
"#,
        project_name = project_name,
        domain = domain,
        doc_root = doc_root,
        ssl_dir = ssl_dir,
        php_pool_port = php_pool_port,
    )
}
